(function ($) {

	"use strict";

	window.CX =
		window.CX || {};


	/**
	 * Initialize frontend product components that can render before a
	 * shopper has selected a variation.
	 */
	CX.init = function () {

		/*
		|--------------------------------------------------------------------------
		| Quantity
		|--------------------------------------------------------------------------
		*/

		if (
			typeof CX.renderQty
			=== "function"
		) {
			CX.renderQty();
		}


		/*
		|--------------------------------------------------------------------------
		| Printing
		|--------------------------------------------------------------------------
		*/

		if (
			typeof CX.renderPrinters
			=== "function"
		) {
			CX.renderPrinters();
		}


		/*
		|--------------------------------------------------------------------------
		| Tier Pricing Table
		|--------------------------------------------------------------------------
		*/

		if (
			typeof CX.updateTable
			=== "function"
		) {
			CX.updateTable();
		}


		/*
		|--------------------------------------------------------------------------
		| Order Summary
		|--------------------------------------------------------------------------
		*/

		if (
			typeof CX.updateSummary
			=== "function"
		) {
			CX.updateSummary();
		}


		/*
		|--------------------------------------------------------------------------
		| Application Ready
		|--------------------------------------------------------------------------
		*/

		$(document).trigger(
			"pdxw:frontend:ready",
			[
				CX
			]
		);
	};


	/*
	|--------------------------------------------------------------------------
	| DOM Ready
	|--------------------------------------------------------------------------
	*/

	$(function () {

		CX.init();

	});

})(jQuery);